// Writes src/composition/locales/<lang>.ts: one bundle per language with the shared
// dictionary and every feature's i18n/<lang>.ts. Run after adding a feature or a language:
//   node apps/web/scripts/i18n-registry.mjs
import { existsSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const web = join(dirname(fileURLToPath(import.meta.url)), "..");
const LANGS = ["pt", "es", "ru", "zh", "de", "fr", "pl", "tr"];
const features = readdirSync(join(web, "src/features"), { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort();
const ident = (s) => s.replace(/-(\w)/g, (_, c) => c.toUpperCase());
for (const lang of LANGS) {
  const owners = features.filter((f) =>
    existsSync(join(web, "src/features", f, "i18n", `${lang}.ts`)),
  );
  const lines = [
    `// Generated by scripts/i18n-registry.mjs: every ${lang} dictionary, loaded as one chunk.`,
    `import { mergeDictionaries } from "@/shared/i18n/core";`,
    `import { ${lang} as shared } from "@/shared/i18n/${lang}";`,
    ...owners.map(
      (f) =>
        `import { ${lang} as ${ident(f)} } from "@/features/${f}/i18n/${lang}";`,
    ),
    "",
    `export const parts = {`,
    `  shared,`,
    ...owners.map((f) => `  ${ident(f)},`),
    `};`,
    `const merged = mergeDictionaries(parts);`,
    `/** Keys translated differently by two parts (must stay empty; see i18n.test.ts). */`,
    `export const conflicts = merged.conflicts;`,
    `export const dictionary = merged.merged;`,
    "",
  ];
  writeFileSync(
    join(web, "src/composition/locales", `${lang}.ts`),
    lines.join("\n"),
  );
}
console.log(`locales: ${LANGS.join(", ")}; features: ${features.length}`);
